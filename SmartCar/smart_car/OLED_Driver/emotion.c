void set_emotion(const char* emotion)
{
    const uint8_t *bits = NULL;
    uint8_t w = 0, h = 0;
    
    if (strcmp(emotion, "neutral") == 0) {
        bits = neutral_bits; w = NEUTRAL_W; h = NEUTRAL_H;
    } else if (strcmp(emotion, "happy") == 0) {
        bits = happy_bits; w = HAPPY_W; h = HAPPY_H;
    } else if (strcmp(emotion, "laughing") == 0) {
        bits = laughing_bits; w = LAUGHING_W; h = LAUGHING_H;
    } else if (strcmp(emotion, "funny") == 0) {
        bits = funny_bits; w = FUNNY_W; h = FUNNY_H;
    } else if (strcmp(emotion, "sad") == 0) {
        bits = sad_bits; w = SAD_W; h = SAD_H;
    } else if (strcmp(emotion, "angry") == 0) {
        bits = angry_bits; w = ANGRY_W; h = ANGRY_H;
    } else if (strcmp(emotion, "crying") == 0) {
        bits = crying_bits; w = CRYING_W; h = CRYING_H;
    } else if (strcmp(emotion, "loving") == 0) {
        bits = loving_bits; w = LOVING_W; h = LOVING_H;
    } else if (strcmp(emotion, "surprised") == 0) {
        bits = surprised_bits; w = SURPRISED_W; h = SURPRISED_H;
    } else if (strcmp(emotion, "shocked") == 0) {
        bits = shocked_bits; w = SHOCKED_W; h = SHOCKED_H;
    } else if (strcmp(emotion, "thinking") == 0) {
        bits = thinking_bits; w = THINKING_W; h = THINKING_H;
    } else if (strcmp(emotion, "cool") == 0) {
        bits = cool_bits; w = COOL_W; h = COOL_H;
    } else if (strcmp(emotion, "sleepy") == 0) {
        bits = sleepy_bits; w = SLEEPY_W; h = SLEEPY_H;
    } else {
        return;
    }
    
    if (bits) {
        OLED_Clear();
        uint8_t x = (128 - w) / 2;
        uint8_t y = (32 - h) / 2;
        OLED_DrawBitmap_Raw(x, y, w, h, bits);
    }
}

void emotion_display_init(void)
{
    set_emotion("neutral");
}

